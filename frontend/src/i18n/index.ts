/**
 * 获取翻译文本的辅助函数
 */
export function t(key: string, fallback?: string): string {
  const keys = key.split('.');
  let obj: any = zhCN;
  
  for (const k of keys) {
    if (obj && obj[k] !== undefined) {
      obj = obj[k];
    } else {
      return fallback || key;
    }
  }
  
  return typeof obj === 'string' ? obj : key;
}
